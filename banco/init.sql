CREATE TABLE pedidos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente         VARCHAR(150)  NOT NULL,
    valor           NUMERIC(10,2) NOT NULL,
    status          VARCHAR(25)   NOT NULL DEFAULT 'CRIADO',
    criado_em       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    previsao_envio  TIMESTAMPTZ,

    CONSTRAINT pedidos_valor_positivo CHECK (valor > 0),
    CONSTRAINT pedidos_status_valido CHECK (status IN (
        'CRIADO',
        'AGUARDANDO_PAGAMENTO',
        'PAGO',
        'ENVIO_AGENDADO',
        'ENVIADO',
        'CANCELADO'
    ))
);

CREATE INDEX idx_pedidos_status ON pedidos (status);

CREATE TABLE boletos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- unique: se a mensagem for reentregue (worker caiu antes do ack) não duplica o boleto
    pedido_id        BIGINT       NOT NULL UNIQUE
                     REFERENCES pedidos (id) ON DELETE CASCADE,
    linha_digitavel  VARCHAR(60)  NOT NULL,
    vencimento       TIMESTAMPTZ  NOT NULL,
    gerado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- hostname do worker, para ver a divisão entre as réplicas
    gerado_por       VARCHAR(64)
);

CREATE INDEX idx_boletos_gerado_em  ON boletos (gerado_em);
CREATE INDEX idx_boletos_vencimento ON boletos (vencimento);

CREATE FUNCTION marcar_atualizado_em() RETURNS TRIGGER AS $$
BEGIN
    NEW.atualizado_em := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pedidos_atualizado_em
    BEFORE UPDATE ON pedidos
    FOR EACH ROW EXECUTE FUNCTION marcar_atualizado_em();
